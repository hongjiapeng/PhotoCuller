using PhotoCuller.Core.Enums;

namespace PhotoCuller.Core.Models;

/// <summary>
/// Complete information for a single photo, including file metadata, EXIF, scores, and processing state.
/// Uses class (not record) because EF Core requires mutable properties for change-tracking writes.
/// Queries default to NoTracking; call Update() explicitly when saving changes.
/// </summary>
public class PhotoItem
{
    public Guid Id { get; set; } = Guid.NewGuid();

    // ── Basic file information ────────────────────────────────────────
    public string FilePath { get; set; } = string.Empty;
    public string FileName { get; set; } = string.Empty;
    public string FileExtension { get; set; } = string.Empty;

    /// <summary>File size in bytes.</summary>
    public long FileSize { get; set; }

    public int Width { get; set; }
    public int Height { get; set; }

    public DateTime? CreatedTime { get; set; }
    public DateTime? ModifiedTime { get; set; }

    /// <summary>EXIF capture time (preferred for burst-shot detection).</summary>
    public DateTime? ExifTakenTime { get; set; }

    // ── Hashes ───────────────────────────────────────────────────────
    /// <summary>SHA-256 hex string used for exact-duplicate detection.</summary>
    public string? Sha256Hash { get; set; }

    /// <summary>Perceptual hash (64-bit DCT) used for similar-photo detection.</summary>
    public ulong? PerceptualHash { get; set; }

    // ── Thumbnail ────────────────────────────────────────────────────
    /// <summary>Thumbnail path on disk (relative to the thumbnail cache root).</summary>
    public string? ThumbnailPath { get; set; }

    // ── Scores (0-100; null means not yet scored) ────────────────────
    public float? OverallScore { get; set; }
    public float? SharpnessScore { get; set; }
    public float? ExposureScore { get; set; }
    public float? ContrastScore { get; set; }
    public float? NoiseScore { get; set; }
    public float? ResolutionScore { get; set; }
    public float? CompositionScore { get; set; }
    public float? ColorScore { get; set; }

    /// <summary>Face quality score (only populated when a face is detected).</summary>
    public float? FaceQualityScore { get; set; }

    // ── Processing state ─────────────────────────────────────────────
    public RecommendationStatus RecommendationStatus { get; set; }
        = RecommendationStatus.Unprocessed;

    /// <summary>ID of the similar-photo group this photo belongs to (null = ungrouped).</summary>
    public Guid? GroupId { get; set; }

    /// <summary>Tags generated by AI / algorithms; stored as a serialized JSON array.</summary>
    public List<string> Tags { get; set; } = [];

    /// <summary>Timestamp of the most recent scan.</summary>
    public DateTime? ScanTime { get; set; }

    /// <summary>Reason for the last analysis failure (null = no error).</summary>
    public string? ErrorMessage { get; set; }

    /// <summary>Algorithm version; a version bump triggers re-analysis.</summary>
    public int AnalysisVersion { get; set; }

    /// <summary>Soft-delete flag indicating the photo has been moved to the pending-delete folder.</summary>
    public bool IsMovedToTrash { get; set; }

    // ── Navigation properties ────────────────────────────────────────
    public PhotoGroup? Group { get; set; }
}
